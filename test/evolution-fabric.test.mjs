function init(t){const dir=fs.mkdtempSync(path.join(os.tmpdir(),'aeos-fabric-'));const e=new EditionRuntime(dir);
 t.after(()=>{e.close();fs.rmSync(dir,{recursive:true,force:true});});
 const aa=e.bootstrapTenant('Synthetic A'),bb=e.bootstrapTenant('Synthetic B'),a=e.auth(aa.token),b=e.auth(bb.token),auditor=e.auth(e.addPrincipal(a,'auditor').token),security=e.auth(e.addPrincipal(a,'security').token);
 const evol=new EvolutionOS(e);evol.init(a);
 const reviewer=crypto.generateKeyPairSync('ed25519');const mirror=evol.createAgent(a,{name:'Independent mirror',role:'mirror',capability:'HACKATHON',public_key:reviewer.publicKey.export({format:'pem',type:'spki'})});
 const worker=evol.createAgent(a,{name:'Evidence evaluator',role:'productive',capability:'HACKATHON'});
 const fab=new EvolutionFabric(e,{evolution:evol});return {e,evol,fab,a,b,auditor,security,mirror,worker,reviewer};}
function provision(f){const ed=f.e.newEdition(f.a,{title:'Synthetic pilot',baseline:'Baseline',rubric:[{key:'quality',weight:.7},{key:'risk',weight:.3}]});
 const participant=f.e.register(f.a,ed.id,'anon_001'),sub=f.e.submit(f.a,ed.id,participant.id,'Synthetic solution');
 const bytes=Buffer.from('Synthetic demonstration only');const hash=crypto.createHash('sha256').update(bytes).digest('hex');
 f.e.run('INSERT INTO artifacts VALUES(?,?,?,?,?,?,?,?,?,?)','art_test01',f.a.tenant,ed.id,sub.id,'readme.md',hash,bytes.length,'CLEAN','MOCK_SCAN_NOT_AUTHENTICATED','local-fixture.bin');
 f.e.run('INSERT INTO gates VALUES(?,?,?,?,?,?,?,?)','gate_test01',f.a.tenant,ed.id,'G3',f.security.id,'LOCAL_REVIEW_ONLY','LOCAL_FIXTURE',new Date().toISOString());
 return {ed,sub};}
test('Discovery and Evolution connect with scoped synthetic hashes, idempotency, and drift protection',t=>{const f=init(t),x=provision(f);
 const one=f.fab.bridgeSubmission(f.a,x.sub.id);assert.equal(one.redacted,true);assert.ok(one.task.startsWith('task_'));
 const old=f.fab.bridgeSubmission(f.a,x.sub.id);assert.equal(old.idempotent,true);assert.equal(old.task,one.task);
 assert.equal(f.fab.health(f.a).bridges[0].count,1);
 assert.throws(()=>f.fab.bridgeSubmission(f.b,x.sub.id),/not found/i);
 f.e.run('UPDATE editions SET rubric=? WHERE tenant=? AND id=?','[]',f.a.tenant,x.ed.id);
 assert.throws(()=>f.fab.bridgeSubmission(f.a,x.sub.id),/drift/);
});
