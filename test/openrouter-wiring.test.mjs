import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {EditionRuntime} from '../src/edition-runtime.mjs';
import {openRouterFree} from '../src/openrouter-free.mjs';
import {SyntheticJobQueue} from '../src/job-queue.mjs';
const rubric=[{key:'execution',weight:0.7},{key:'evidence',weight:0.3}];
test('Trusted mock OpenRouter request through REAL SQLite queue and stored job, never sending participant identity',async t=>{
 const old=process.env.AIFIRST_SYNTHETIC_DEMO;process.env.AIFIRST_SYNTHETIC_DEMO='1';
 t.after(()=>{if(old===undefined)delete process.env.AIFIRST_SYNTHETIC_DEMO;else process.env.AIFIRST_SYNTHETIC_DEMO=old;});
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'aifirst-provider-e2e-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const captured=[];
 const agentFetch=async(url,args)=>{
  const p=JSON.parse(args.body),user=JSON.parse(p.messages[1].content);captured.push({url,model:p.model,user,authorization:args.headers.Authorization});
  return {ok:true,json:async()=>({model:'openrouter/free',choices:[{message:{content:'Evidence is insufficient to make a personnel decision. Human review required.'}}],usage:{prompt_tokens:48,completion_tokens:12}})};
 };
 const engine=new EditionRuntime(root,{scanner:async(file,sha)=>({status:'CLEAN',reference:'LOCAL_TEST_ONLY',sha256:sha,signature_valid:true})});t.after(()=>engine.close());
 engine.agent=openRouterFree({apiKey:'sk-or-'+('a'.repeat(24)),db:engine.db,fetchImpl:agentFetch,perDay:1});
 const tenant=engine.bootstrapTenant('Synthetic org'),admin=engine.auth(tenant.token);
 const sponsor=engine.auth(engine.addPrincipal(admin,'sponsor').token),security=engine.auth(engine.addPrincipal(admin,'security').token);
 const edition=engine.newEdition(admin,{title:'Synthetic evaluation',baseline:'Time estimate not confirmed',rubric});
 const participant=engine.register(sponsor,edition.id,'alias_p1'),submission=engine.submit(sponsor,edition.id,participant.id,'Synthetic documentation parser');
 const bytes=Buffer.from('synthetic README with no identifying information'),sha=crypto.createHash('sha256').update(bytes).digest('hex');
 await engine.upload(sponsor,submission.id,'readme.md',bytes,sha);
 engine.gate(security,edition.id,'G3','LOCAL_TEST_ONLY');
 const queue=new SyntheticJobQueue(engine),entry=queue.enqueue(sponsor,submission.id,{maxCostEur:.1});
 const processed=await queue.runOne(admin,'worker_synthetic_1');
 assert.equal(processed.status,'COMPLETED');assert.equal(captured.length,1);
 assert.equal(captured[0].model,'openrouter/free');
 assert.equal(captured[0].user.project,'Synthetic documentation parser');
 assert.equal(JSON.stringify(captured[0].user).includes('alias_p1'),false);
 assert.equal(JSON.stringify(captured[0].user).includes('synthetic README with no identifying information'),false);
 assert.equal(engine.rows('SELECT status FROM jobs WHERE tenant=?',tenant.tenant)[0].status,'PENDING_HUMAN_REVIEW');
 assert.throws(()=>queue.enqueue(sponsor,submission.id,{model:'anthropic/claude-sonnet',maxCostEur:.1}),/Only free/);
 assert.equal((await queue.runOne(admin,'worker_synthetic_2')).status,'EMPTY');
});
