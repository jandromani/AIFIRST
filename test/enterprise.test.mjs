test('OIDC JWT validates RSA signature, issuer, audience, age and mapped tenant',t=>{
 const {engine,admin}=setup(t);
 const {publicKey,privateKey}=crypto.generateKeyPairSync('rsa',{modulusLength:2048});
 const jwk={...publicKey.export({format:'jwk'}),kid:'test1',alg:'RS256',use:'sig'};
 const issuer='https://idp.example.test',audience='aifirst-app';
 const config={issuer,audience,jwks:{keys:[jwk]}};
 const ops=new EnterpriseOps(engine,{oidc:config});
 ops.bindOidc(admin,{issuer,subject:'subject-demo',role:'admin',principal:admin.id});
 const now=Math.floor(Date.now()/1000);
 const b=x=>Buffer.from(JSON.stringify(x)).toString('base64url');
 const header=b({alg:'RS256',kid:'test1'}),payload=b({iss:issuer,aud:audience,sub:'subject-demo',exp:now+3600,iat:now});
 const signed=header+'.'+payload,signature=crypto.sign('sha256',Buffer.from(signed),privateKey).toString('base64url');
 const token=signed+'.'+signature;
 const claims=verifyOidcJwt(token,config);
 assert.equal(claims.verified_signature,true);
 const ctx=ops.authenticateOidc(token);assert.equal(ctx.tenant,admin.tenant);assert.equal(ctx.auth_method,'verified_oidc');
 assert.throws(()=>verifyOidcJwt(signed+'.'+signature.slice(0,-4)+'AAAA',config),/signature|JWT|Invalid/);
 assert.throws(()=>verifyOidcJwt(token,{...config,audience:'wrong'}),/claims/);
 const signer=crypto.generateKeyPairSync('ed25519');
 const registered=ops.registerSigner(ctx,signer.publicKey.export({format:'pem',type:'spki'}));assert.equal(registered.qualified_electronic_signature,false);
 const edition=engine.rows('SELECT id FROM editions WHERE tenant=?',ctx.tenant)[0].id;
 const body=ops.approvalPayload(ctx,edition,'G1','a'.repeat(64));
 const sig=crypto.sign(null,Buffer.from(body),signer.privateKey).toString('base64');
 const signedGate=ops.signGate(ctx,edition,'G1','a'.repeat(64),sig);
 assert.equal(signedGate.oidc_identity_verified,true);assert.equal(signedGate.release_allowed,false);
 assert.equal(ops.approvals(ctx,edition).length,1);
});
